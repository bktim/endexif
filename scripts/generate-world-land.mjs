import { mkdir, readFile, writeFile } from 'node:fs/promises';
import { createRequire } from 'node:module';
import { dirname } from 'node:path';
import { fileURLToPath } from 'node:url';
import { gzipSync } from 'node:zlib';
import { geoEquirectangular, geoPath } from 'd3-geo';
import { feature, mesh } from 'topojson-client';

const WORLD_MAP_WIDTH = 360;
const WORLD_MAP_HEIGHT = 180;
// Budgets derived from measured land + country-border digits(1) output (~172 KB gzip):
// target ≈ +10%, hard cap ≈ +25%.
const GZIP_TARGET_BYTES = 190_000;
const GZIP_HARD_LIMIT_BYTES = 216_000;
const OUTPUT_URL = new URL('../src/generated/worldLandPath.ts', import.meta.url);
const require = createRequire(import.meta.url);

function renderModule(landPath, borderPath) {
  return [
    '// Generated by npm run generate:map. Do not edit manually.',
    '// Source: Natural Earth countries-50m via world-atlas@2.0.2.',
    '// Generated with topojson-client@3.1.0 and d3-geo@3.1.1.',
    '// Natural Earth data is public domain; generation tools are ISC licensed.',
    `export const WORLD_MAP_WIDTH = ${WORLD_MAP_WIDTH};`,
    `export const WORLD_MAP_HEIGHT = ${WORLD_MAP_HEIGHT};`,
    `export const WORLD_LAND_PATH = ${JSON.stringify(landPath)};`,
    `export const WORLD_BORDER_PATH = ${JSON.stringify(borderPath)};`,
    '',
  ].join('\n');
}

async function generateModule() {
  const atlasPath = require.resolve('world-atlas/countries-50m.json');
  const topology = JSON.parse(await readFile(atlasPath, 'utf8'));
  const land = feature(topology, topology.objects.land);
  const borders = mesh(topology, topology.objects.countries, (a, b) => a !== b);
  const projection = geoEquirectangular()
    .scale(WORLD_MAP_WIDTH / (2 * Math.PI))
    .translate([WORLD_MAP_WIDTH / 2, WORLD_MAP_HEIGHT / 2]);
  const path = geoPath(projection).digits(1);
  const landPath = path(land);
  const borderPath = path(borders);

  if (!landPath || !borderPath) {
    throw new Error('Natural Earth countries-50m produced an empty land or border path.');
  }

  return renderModule(landPath, borderPath);
}

function enforceGzipBudget(output) {
  const gzipBytes = gzipSync(output).length;

  if (gzipBytes > GZIP_TARGET_BYTES) {
    console.warn(
      `Warning: generated world land module is ${gzipBytes} bytes gzip, above ${GZIP_TARGET_BYTES}-byte target (${GZIP_HARD_LIMIT_BYTES}-byte hard cap).`,
    );
  }

  if (gzipBytes > GZIP_HARD_LIMIT_BYTES) {
    throw new Error(
      `Generated world land module is ${gzipBytes} bytes gzip, exceeding ${GZIP_HARD_LIMIT_BYTES}-byte hard cap.`,
    );
  }
}

async function checkGeneratedModule(expected) {
  let actual;

  try {
    actual = await readFile(OUTPUT_URL);
  } catch (error) {
    if (error && error.code === 'ENOENT') {
      console.error('Generated world land path is missing. Run `npm run generate:map` to regenerate it.');
      process.exitCode = 1;
      return;
    }
    throw error;
  }

  if (!actual.equals(Buffer.from(expected, 'utf8'))) {
    console.error('Generated world land path is stale. Run `npm run generate:map` to regenerate it.');
    process.exitCode = 1;
    return;
  }

  console.log('Generated world land path is up to date.');
}

async function main() {
  const args = process.argv.slice(2);
  const check = args.length === 1 && args[0] === '--check';

  if (args.length > 0 && !check) {
    console.error('Usage: node scripts/generate-world-land.mjs [--check]');
    process.exitCode = 2;
    return;
  }

  const output = await generateModule();
  enforceGzipBudget(output);

  if (check) {
    await checkGeneratedModule(output);
    return;
  }

  await mkdir(dirname(fileURLToPath(OUTPUT_URL)), { recursive: true });
  await writeFile(OUTPUT_URL, output, 'utf8');
  console.log('Generated src/generated/worldLandPath.ts.');
}

await main();
